"""Write a browsable index.html into every directory of a built site.

Usage: listing.py SITE

The pages are for people looking around; no package manager reads them, and
each says so and points at the setup steps on the landing page. A directory
lists its files and subdirectories, and also the packages that are not files
of the site: each .deb under apt/pool/ and each .apk redirects to its GitHub
Release asset, and dnf fetches each .rpm from GitHub directly
(manifest.json names them all).

Every directory is also given a redirect from its name without the trailing
slash, appended to SITE/_redirects, so /apk/nightly works as /apk/nightly/ does.
The landing page is the root's index.html; the root gets no listing.
"""

import html
import json
import sys
from pathlib import Path
from urllib.parse import quote

site = Path(sys.argv[1])
manifest = json.loads((site / "manifest.json").read_text())
esc = html.escape

# What each tree is for, said at the top of every page in it.
HINTS = {
    "apt": "apt reads <code>dists/&lt;channel&gt;/InRelease</code> and the <code>Packages</code> lists it signs; "
           "each <code>.deb</code> under <code>pool/</code> redirects to the GitHub Release it was published in.",
    "rpm": "dnf reads <code>&lt;channel&gt;/repodata/repomd.xml</code> and its signature, "
           "then fetches each <code>.rpm</code> straight from GitHub Releases.",
    "apk": "apk reads <code>&lt;channel&gt;/&lt;arch&gt;/APKINDEX.tar.gz</code>; "
           "each <code>.apk</code> redirects to the GitHub Release it was published in.",
    "macports": "MacPorts fetches <code>&lt;channel&gt;/ports.tar</code> and checks it against "
                "<code>ports.tar.sig</code>; each port then downloads its build from GitHub Releases.",
    "keys": "The public keys the setup steps install: <code>nemo-packages.gpg</code> (apt) and "
            "<code>nemo-packages.asc</code> (dnf), the <code>.rsa.pub</code> key (apk) and "
            "<code>nemo-macports.pub</code> (MacPorts).",
}

# directory ("apt/dists") -> {entry name ("nightly/" or "InRelease"): (size, href, where)}
tree = {}


def add(path, size, href=None, where=""):
    parts = path.split("/")
    for depth in range(1, len(parts)):
        tree.setdefault("/".join(parts[:depth]), {})
        if depth > 1:
            tree["/".join(parts[:depth - 1])][parts[depth - 1] + "/"] = (None, quote(parts[depth - 1]) + "/", "")
    tree["/".join(parts[:-1])][parts[-1]] = (size, href or quote(parts[-1]), where)


for f in sorted(site.rglob("*")):
    rel = f.relative_to(site).as_posix()
    if f.is_file() and "/" in rel and f.name != "index.html":
        add(rel, f.stat().st_size)

for p in manifest:
    if p["format"] == "deb":
        add(f"apt/pool/{p['repo']}/{p['tag']}/{p['asset']}", p["size"], where="redirects to GitHub Releases")
    elif p["format"] == "apk":
        add(f"apk/{p['channel']}/{p['arch']}/{p['package']}-{p['version']}.apk", p["size"],
            where="redirects to GitHub Releases")
    elif p["format"] == "rpm":
        add(f"rpm/{p['channel']}/{p['asset']}", p["size"], href=p["url"], where="on GitHub Releases")


def size_text(n):
    if n is None:
        return ""
    for unit in ("B", "KB", "MB"):
        if n < 1024 or unit == "MB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def page(directory, entries):
    hint = HINTS.get(directory.split("/")[0], "")
    names = sorted(entries, key=lambda n: (not n.endswith("/"), n))
    rows = "\n".join(
        f"<tr><td><a href=\"{esc(entries[n][1])}\">{esc(n)}</a></td>"
        f"<td class=\"size\">{size_text(entries[n][0])}</td><td>{esc(entries[n][2])}</td></tr>"
        for n in names)
    return f"""<!doctype html>
<meta charset="utf-8">
<title>Index of /{esc(directory)}/ - Nemo's Packages</title>
<style>body{{font:15px/1.5 system-ui,sans-serif;max-width:60rem;margin:2rem auto;padding:0 1rem}}
.note{{background:#fff8e1;border-left:4px solid #f0b400;padding:.6rem .9rem}}
td,th{{padding:.1rem .6rem;font-size:13px;text-align:left}}td.size{{text-align:right;white-space:nowrap}}</style>
<h1>Index of /{esc(directory)}/</h1>
<p class="note"><strong>This page is generated automatically</strong> each time the site is built, for
looking around; no package manager reads it. To install anything, set up apt, dnf, apk or MacPorts as
<a href="/">the front page</a> shows, then install with your package manager as usual. {hint}</p>
<table><tr><th>Name</th><th>Size</th><th></th></tr>
<tr><td><a href="../">../</a></td><td></td><td></td></tr>
{rows}</table>
"""


for directory, entries in tree.items():
    (site / directory).mkdir(parents=True, exist_ok=True)
    (site / directory / "index.html").write_text(page(directory, entries))

with open(site / "_redirects", "a") as rules:
    rules.write("# Generated by scripts/listing.py: a directory without its trailing slash.\n")
    for directory in sorted(tree):
        rules.write(f"/{directory} /{directory}/ 301\n")
print(f"{len(tree)} directory listings")
