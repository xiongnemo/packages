"""Write a MacPorts ports tree per channel from the projects' darwin builds.

Usage: macports.py PROJECTS_JSON WORK SITE [--include OWNER/REPO@TAG ...]

A ports tree holds one version of each port, so each channel gets the newest
release of each project that carries darwin builds: prereleases for `nightly`,
releases for `stable`, the same split as the other formats. Every Portfile is a
binary port: it fetches the prebuilt arm64 or x86_64 file from the GitHub
Release, checks it against the sha256 and size computed here from the
downloaded file (and checked against GitHub's digest), and installs the one
executable into ${prefix}/bin.

  WORK/macports-<channel>/ports/<category>/<port>/Portfile

index.sh tars each tree and signs it. Projects opt in with a `macports` object
in projects.json: port name, binary name, category, license, description.
"""

import json
import re
import sys
import tarfile
from pathlib import Path

from collect import download, releases, sha256

# Projects spell the platform with a hyphen (saki-...-darwin-arm64.tar.gz) or an
# underscore (tsumugi_..._darwin_arm64.tar.gz); either names the same build.
ARCHES = {"arm64": ("darwin-arm64", "darwin_arm64"), "x86_64": ("darwin-amd64", "darwin_amd64")}


def darwin_assets(release):
    found = {}
    for arch, markers in ARCHES.items():
        for asset in release["assets"]:
            name = asset["name"]
            if asset["state"] != "uploaded":
                continue
            if any(m in name and (name.endswith(".tar.gz") or name.endswith(m)) for m in markers):
                found[arch] = asset
                break
    return found


def fetch(repo, tag, asset, cache):
    cached = cache / f"{asset['id']}-{asset['name']}"
    declared = (asset.get("digest") or "").removeprefix("sha256:")
    if not cached.exists() or (declared and sha256(cached) != declared):
        download(asset["browser_download_url"], cached)
    actual = sha256(cached)
    if declared and actual != declared:
        sys.exit(f"{repo} {tag} {asset['name']}: downloaded sha256 {actual}, GitHub reports {declared}")
    return cached, actual


def executable_in(archive, binary):
    """The archive member to install: an executable regular file named for the binary."""
    with tarfile.open(archive, "r:gz") as tar:
        members = [m for m in tar.getmembers()
                   if m.isfile() and m.mode & 0o111 and Path(m.name).name.startswith(binary)
                   and not m.name.endswith(".sha256")]
    if not members:
        sys.exit(f"{archive.name}: no executable named {binary}*")
    return min(members, key=lambda m: len(m.name)).name.removeprefix("./")


def tcl_text(value):
    """A Tcl word that is exactly the given text."""
    assert "{" not in value and "}" not in value and "\\" not in value, value
    return "{" + value + "}"


def portfile(project, release, files):
    config = project["macports"]
    repo, tag = project["repo"], release["tag_name"]
    version = re.match(r"v?(\d+\.\d+\.\d+)", tag).group(1)
    arch_blocks = []
    for arch, (asset_name, digest, size, member) in files.items():
        if member is None:
            install = f"set nemo_source ${{distpath}}/{asset_name}"
        else:
            install = f"set nemo_source ${{worksrcpath}}/{member}"
        arch_blocks.append(f"""    {arch} {{
        distfiles           {asset_name}
        checksums           sha256 {digest} \\
                            size {size}
        {install}
    }}""")
    archive = any(member is not None for *_, member in files.values())
    extract = "extract.mkdir        yes" if archive else "extract {\n    file mkdir ${worksrcpath}\n}"
    return f"""# -*- coding: utf-8; mode: tcl; tab-width: 4; indent-tabs-mode: nil; c-basic-offset: 4 -*- vim:fenc=utf-8:ft=tcl:et:sw=4:ts=4:sts=4
# Generated by xiongnemo/packages scripts/macports.py from {repo} {tag}.

PortSystem          1.0

name                {config['port']}
version             {version}
revision            0
categories          {config['category']}
license             {config.get('license', 'unknown')}
maintainers         nomaintainer
platforms           darwin
supported_archs     {' '.join(sorted(files))}
installs_libs       no
universal_variant   no

description         {tcl_text(config['description'])}
long_description    {tcl_text(config['description'] + f' This port installs the prebuilt {tag} binary published on GitHub Releases.')}
homepage            https://github.com/{repo}
master_sites        https://github.com/{repo}/releases/download/{tag}/

switch ${{configure.build_arch}} {{
{chr(10).join(arch_blocks)}
}}

{extract}
use_configure       no
build {{}}

destroot {{
    xinstall -m 0755 ${{nemo_source}} ${{destroot}}${{prefix}}/bin/{config['binary']}
}}
"""


def main():
    projects_file, work, site = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    includes = {}
    args = sys.argv[4:]
    while args:
        flag, value, args = args[0], args[1], args[2:]
        assert flag == "--include", flag
        repo, _, tag = value.partition("@")
        includes.setdefault(repo, []).append(tag)

    cache = work / "cache"
    cache.mkdir(parents=True, exist_ok=True)
    manifest_path = site / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else []

    for project in json.loads(projects_file.read_text())["projects"]:
        config = project.get("macports")
        if not config:
            continue
        repo = project["repo"]
        done = set()
        for release in releases(repo, includes):
            channel = "nightly" if release["prerelease"] else "stable"
            assets = darwin_assets(release)
            if channel in done or not assets:
                continue
            done.add(channel)
            tag = release["tag_name"]
            files = {}
            for arch, asset in assets.items():
                path, digest = fetch(repo, tag, asset, cache)
                member = executable_in(path, config["binary"]) if asset["name"].endswith(".tar.gz") else None
                files[arch] = (asset["name"], digest, path.stat().st_size, member)
                manifest.append({"repo": repo, "tag": tag, "channel": channel, "format": "macports",
                                 "asset": asset["name"], "sha256": digest, "size": path.stat().st_size,
                                 "url": f"https://github.com/{repo}/releases/download/{tag}/{asset['name']}"})
            target = work / f"macports-{channel}" / "ports" / config["category"] / config["port"] / "Portfile"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(portfile(project, release, files))
            print(f"{channel:8} macports {repo} {tag} ({', '.join(sorted(files))})", flush=True)

    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
